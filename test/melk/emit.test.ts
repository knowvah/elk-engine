describe('RecordingRegistry names from the generator', () => {
  it('derives nested class paths from the imports of the sources', () => {
    expect(
      nestedClassPaths(['a.b.Outer.Inner', 'a.b.Plain', 'org.eclipse.elk.core.^labels.ILabelManager']).get('Inner'),
    ).toBe('Outer.Inner');
    expect(nestedClassPaths(['a.b.Plain']).size).toBe(0);
    const recorder = new RecordingRegistry();
    recorder.addOptionSupport('a', 'other', new PackingMode());
    expect(recorder.calls[0]).toMatchObject({
      default: { t: 'enum', c: 'BoxLayoutProvider.PackingMode', n: 'SIMPLE' },
    });
  });

  it('names a nested enum set element class as Outer.Inner and leaves other names alone', () => {
    const recorder = new RecordingRegistry({ nestedClasses: new Map([['SizeOptions', 'Outer.SizeOptions']]) });
    recorder.addOptionSupport('a', 'other', SizeOptions.PORTS_OVERHANG);
    recorder.addOptionSupport('a', 'other', new PackingMode());
    expect(recorder.calls.map((c) => (c.call === 'addOptionSupport' ? c.default : null))).toEqual([
      { t: 'enum', c: 'Outer.SizeOptions', n: 'PORTS_OVERHANG' },
      { t: 'enum', c: 'PackingMode', n: 'SIMPLE' },
    ]);
  });

  it('records the JVM binary name of a generated factory', () => {
    const names = factoryClassNames();
    expect(names.get('FixedFactory')).toBe('org.eclipse.elk.core.options.FixedLayouterOptions$FixedFactory');
    expect(names.get('LayeredFactory')).toBe('org.eclipse.elk.alg.layered.options.LayeredOptions$LayeredFactory');
    for (const algorithm of resolveWith([]).flatMap((bundle) => bundle.algorithms)) {
      expect(names.get(algorithm.factoryName)).toBe(algorithm.data.factoryClass);
    }
    const recorder = new RecordingRegistry();
    recorder.register(
      new LayoutAlgorithmData.Builder()
        .id('org.eclipse.elk.fixed')
        .name('ELK Fixed')
        .providerFactory(new FixedFactory())
        .create(),
    );
    expect(recorder.calls[0]).toMatchObject({
      data: { factoryClass: 'org.eclipse.elk.core.options.FixedLayouterOptions$FixedFactory' },
    });
  });

  it('keeps the class name of a factory the model does not know', () => {
    const recorder = new RecordingRegistry({ factoryClasses: new Map() });
    recorder.register(new LayoutAlgorithmData.Builder().id('x').name('X').providerFactory(new FixedFactory()).create());
    expect(recorder.calls[0]).toMatchObject({ data: { factoryClass: 'FixedFactory' } });
  });
});

