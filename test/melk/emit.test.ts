function resolveWith(pendingTypes: readonly string[]): ResolvedBundle[] {
  return resolveAll(MELK_NAMES.map(parseVendored), { pendingTypes });
}

/** Resolves a synthetic file and returns the text of its bundle class. */
async function emitSnippet(
  members: string,
  pendingTypes: readonly string[] = [],
  imports = '',
): Promise<Map<string, string>> {
  const text = `package org.example\nimport java.util.EnumSet\nimport java.util.List\n${imports}\nbundle {\n label "Ex"\n metadataClass options.ExampleOptions\n idPrefix org.example\n}\n${members}`;
  const [bundle] = resolveAll([parseMelk(text, 'Example.melk')], { pendingTypes, upstreamPaths: new Map() });
  if (bundle === undefined) {
    throw new Error('snippet did not resolve');
  }
  return emitBundle(bundle);
}

/** Collapses the layout prettier chose, so that expectations name only the code. */
function flatten(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/\( /g, '(').replace(/,? \)/g, ')');
}

async function bundleText(members: string, pendingTypes: readonly string[] = [], imports = ''): Promise<string> {
  const text = [...(await emitSnippet(members, pendingTypes, imports))].find(([path]) =>
    path.endsWith('ExampleOptions.ts'),
  );
  if (text === undefined) {
    throw new Error('no bundle file');
  }
  return flatten(text[1]);
}

