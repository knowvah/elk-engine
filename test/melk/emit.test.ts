    const imports = new ImportCollector('src/core/x/A.ts');
    const context = { scope: new Map<string, string>(), defaultPackage: 'org.eclipse.elk.core.x', imports };
    const type = (name: string, args: string[] = []): string =>
      tsTypeOf({ name, args: args.map((a) => ({ name: a, args: [] })) }, context);
