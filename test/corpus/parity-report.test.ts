import { describe, expect, it } from "vitest";
import type { Census, CensusModel } from "../../tools/corpus/census.js";
import {
  type ReportContext,
  type SweepSummary,
  isStale,
  parsePatches,
  parseResults,
  parseSummary,
  renderReport,
} from "../../tools/corpus/parity-report.js";
import type { SweepRecord, Tier, Verdict } from "../../tools/corpus/sweep.js";

const PREFIX = "org.eclipse.elk.";
const LAYERED = `${PREFIX}layered`;
const SPORE = `${PREFIX}sporeOverlap`;
const FIXED = `${PREFIX}fixed`;
const PATCH = "0001-graph.json-seedable-JsonExporter-id-collision-random.patch";
const ELK_COMMIT = "a".repeat(40);
const MODELS_COMMIT = "b".repeat(40);
const NO_CASES_CELL = "— (no cases)";
const NO_NATIVE_CELL = "— (no model has it at the root)";

let seq = 0;
function rec(tier: Tier, algorithm: string, verdict: Verdict): SweepRecord {
  seq += 1;
  const modelId = `tests/m${seq}`;
  return {
    caseId: `${tier}/${algorithm}/default/${modelId}`,
    tier,
    algorithm,
    variant: "default",
    modelId,
    verdict,
    ms: 1,
  };
}

const RESULTS: SweepRecord[] = [
  rec("native", LAYERED, "ok"),
  rec("native", LAYERED, "ok"),
  rec("native", LAYERED, "throws"),
  rec("retarget", SPORE, "ok"),
  rec("retarget", SPORE, "nondeterministic"),
  rec("retarget", SPORE, "timeout"),
  rec("generated", SPORE, "nondeterministic"),
  rec("retarget", LAYERED, "ok"),
];

const SUMMARY: SweepSummary = {
  elkCommit: ELK_COMMIT,
  modelsCommit: MODELS_COMMIT,
  cases: RESULTS.length,
  wallMs: 129224,
  parseErrors: [],
};

function model(id: string, rootAlgorithm: string): CensusModel {
  return {
    id,
    folder: id.split("/")[0] as CensusModel["folder"],
    source: "elkt",
    formats: ["elkt"],
    parse: "ok",
    nodes: 1,
    edges: 0,
    ports: 0,
    labels: 0,
    maxDepth: 1,
    declaredAlgorithms: [],
    rootAlgorithm,
  };
}

const CENSUS: Census = {
  modelsCommit: MODELS_COMMIT,
  elkCommit: ELK_COMMIT,
  count: 3,
  models: [
    model("examples/a", LAYERED),
    model("tests/b", LAYERED),
    model("tickets/c", LAYERED),
  ],
};

const CONTEXT: ReportContext = {
  algorithms: [SPORE, LAYERED, FIXED],
  patches: [PATCH],
};

function render(): string {
  return renderReport(RESULTS, SUMMARY, CENSUS, CONTEXT);
}

/** Cells of the table whose header row starts with `firstHeader`, keyed by first cell. */
function tableRows(md: string, firstHeader: string): Map<string, string[]> {
  const lines = md.split("\n");
  const start = lines.findIndex((l) => l.startsWith(`| ${firstHeader} |`));
  const rows = new Map<string, string[]>();
  for (const line of lines.slice(start + 2)) {
    if (!line.startsWith("|")) break;
    const cells = line
      .split("|")
      .slice(1, -1)
      .map((c) => c.trim());
    rows.set(cells[0] as string, cells.slice(1));
  }
  return rows;
}

describe("renderReport", () => {
  it("starts with the GENERATED comment then the SPDX comment", () => {
    const lines = render().split("\n");
    expect(lines[0]).toBe(
      "<!-- GENERATED by tools/corpus/parity-report.ts — do not edit by hand -->",
    );
    expect(lines[1]).toBe("<!-- SPDX-License-Identifier: EPL-2.0 -->");
  });

  it("states commits, patches, case count and wall time rounded to the minute", () => {
    const md = render();
    expect(md).toContain(`ELK commit: \`${ELK_COMMIT}\``);
    expect(md).toContain(`Models commit: \`${MODELS_COMMIT}\``);
    expect(md).toContain(`Oracle seam patches: \`${PATCH}\``);
    expect(md).toContain("Cases: 8");
    expect(md).toContain("Sweep wall time: 2 min");
  });

  it("has one row per listed algorithm, sorted, with counts summing to the fixture cases", () => {
    const rows = tableRows(render(), "algorithm");
    expect([...rows.keys()]).toEqual([
      "`fixed`",
      "`layered`",
      "`sporeOverlap`",
    ]);
    // cells: native, retarget, generated, ok, throws, nondeterministic, timeout, oracle-error, ts
    expect(rows.get("`layered`")).toEqual([
      "3",
      "1",
      "— (no generated inputs)",
      "3",
      "1",
      "0",
      "0",
      "0",
      "n/a (no TS port yet)",
    ]);
    expect(rows.get("`sporeOverlap`")).toEqual([
      NO_NATIVE_CELL,
      "3",
      "1",
      "1",
      "0",
      "2",
      "1",
      "0",
      "n/a (no TS port yet)",
    ]);
    const total = [...rows.values()].reduce(
      (sum, cells) =>
        sum + [0, 1, 2].reduce((s, i) => s + (Number(cells[i]) || 0), 0),
      0,
    );
    expect(total).toBe(RESULTS.length);
  });

  it("names why an algorithm without any case has empty cells", () => {
    const cells = tableRows(render(), "algorithm").get("`fixed`");
    expect(cells).toEqual([
      NO_NATIVE_CELL,
      "— (no retarget cases)",
      "— (no generated inputs)",
      NO_CASES_CELL,
      NO_CASES_CELL,
      NO_CASES_CELL,
      NO_CASES_CELL,
      NO_CASES_CELL,
      "n/a (no TS port yet)",
    ]);
  });

  it("leaves no blank cell in any table", () => {
    for (const line of render()
      .split("\n")
      .filter((l) => l.startsWith("|"))) {
      expect(
        line
          .split("|")
          .slice(1, -1)
          .every((c) => c.trim() !== ""),
      ).toBe(true);
    }
  });

  it("counts native census models per folder per algorithm", () => {
    const rows = tableRows(render(), "algorithm (native root)");
    expect(rows.get("`layered`")).toEqual(["1", "1", "1", "— (none)", "3"]);
    expect(rows.get("`fixed`")).toEqual([
      "— (none)",
      "— (none)",
      "— (none)",
      "— (none)",
      NO_NATIVE_CELL,
    ]);
  });

  it("is byte-identical when rendered twice and contains no timestamp", () => {
    expect(render()).toBe(render());
    expect(render()).not.toMatch(/\d{4}-\d{2}-\d{2}T/);
  });

  it("emits nondeterminism sources only for algorithms that have such cases", () => {
    const md = render();
    expect(md).toContain("## Nondeterminism sources");
    expect(md).toContain(
      "- `sporeOverlap` (2 cases): `Math.random()` vertex jitter",
    );
    expect(md).toContain("ElkGraphImporter.java:169");
    expect(md).not.toContain("randomSeed");
    const clean = renderReport(
      [rec("native", LAYERED, "ok")],
      { ...SUMMARY, cases: 1 },
      CENSUS,
      CONTEXT,
    );
    expect(clean).not.toContain("## Nondeterminism sources");
  });

  it("marks an unmapped nondeterministic algorithm as undiagnosed", () => {
    const md = renderReport(
      [rec("retarget", LAYERED, "nondeterministic")],
      { ...SUMMARY, cases: 1 },
      CENSUS,
      CONTEXT,
    );
    expect(md).toContain("- `layered` (1 case): cause not yet diagnosed");
  });

  it("lists parse errors, or says none", () => {
    expect(render()).toContain("Parse errors: none");
    const md = renderReport(
      RESULTS,
      { ...SUMMARY, parseErrors: ["tests/x", "tests/y"] },
      CENSUS,
      CONTEXT,
    );
    expect(md).toContain("Parse errors: `tests/x`, `tests/y`");
  });

  it("rejects results naming an algorithm outside the oracle list", () => {
    const stray = [rec("native", `${PREFIX}ghost`, "ok")];
    expect(() =>
      renderReport(stray, { ...SUMMARY, cases: 1 }, CENSUS, CONTEXT),
    ).toThrow(
      `Result algorithm ${PREFIX}ghost is not in the oracle algorithm list`,
    );
  });

  it("rejects a summary whose case count differs from the results", () => {
    expect(() =>
      renderReport(RESULTS, { ...SUMMARY, cases: 99 }, CENSUS, CONTEXT),
    ).toThrow("summary.json says 99 cases but results.jsonl has 8");
  });
});

describe("parseResults / parseSummary / parsePatches", () => {
  it("round-trips records written as JSON lines", () => {
    const text = `${RESULTS.map((r) => JSON.stringify(r)).join("\n")}\n`;
    expect(parseResults(text)).toEqual(RESULTS);
  });

  it("rejects a line with an unknown verdict", () => {
    const bad = JSON.stringify({ ...RESULTS[0], verdict: "maybe" });
    expect(() => parseResults(bad)).toThrow("results.jsonl line 1");
  });

  it("rejects a line that is not JSON", () => {
    expect(() => parseResults("nope")).toThrow("results.jsonl line 1");
  });

  it("parses a valid summary and rejects a malformed one", () => {
    expect(parseSummary(JSON.stringify(SUMMARY))).toEqual(SUMMARY);
    expect(() =>
      parseSummary(JSON.stringify({ ...SUMMARY, cases: "x" })),
    ).toThrow("summary.json");
  });

  it("reads the patches list of oracle-build.json", () => {
    expect(
      parsePatches(JSON.stringify({ commit: ELK_COMMIT, patches: [PATCH] })),
    ).toEqual([PATCH]);
    expect(() => parsePatches("{}")).toThrow("oracle-build.json");
  });
});

describe("isStale", () => {
  it("is true for a missing file and for different content, false for equal content", () => {
    expect(isStale(undefined, "x")).toBe(true);
    expect(isStale("y", "x")).toBe(true);
    expect(isStale("x", "x")).toBe(false);
  });
});
