import { spawnSync } from 'node:child_process';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadManifest, repoRoot } from '../../test/corpus/corpus.js';
import {
  type Census,
  COMMITTED_CENSUS_RELATIVE,
  DEFAULT_ORACLE_RELATIVE,
  ELK_ALGORITHM_PREFIX,
  ELK_COMMIT_RELATIVE,
  MODEL_FOLDERS,
  ORACLE_DIR_ENV,
  RUN_SCRIPT_RELATIVE,
  WRITE_FLAG,
} from './census.js';
import type { SweepRecord, Tier, Verdict } from './sweep.js';

export interface SweepSummary {
  elkCommit: string;
  modelsCommit: string;
  cases: number;
  wallMs: number;
  parseErrors: string[];
}

/** Inputs that do not come from the sweep cache: the oracle's algorithm list and applied seam patches. */
export interface ReportContext {
  algorithms: readonly string[];
  patches: readonly string[];
}

export const REPORT_RELATIVE = 'docs/parity-report.md';
export const TIERS: readonly Tier[] = ['native', 'retarget', 'generated'];
export const VERDICTS: readonly Verdict[] = ['ok', 'throws', 'nondeterministic', 'timeout', 'oracle-error'];
const GENERATED_HEADER = '<!-- GENERATED by tools/corpus/parity-report.ts — do not edit by hand -->';
const SPDX_HEADER = '<!-- SPDX-License-Identifier: EPL-2.0 -->';
const TS_CONFORMANT_CELL = 'n/a (no TS port yet)';
const NO_CASES_CELL = '— (no cases)';
const NO_NATIVE_CELL = '— (no model has it at the root)';
const NO_FOLDER_CELL = '— (none)';
const TIER_EMPTY_CELLS: Record<Tier, string> = {
  native: NO_NATIVE_CELL,
  retarget: '— (no retarget cases)',
  generated: '— (no generated inputs)',
};
const MS_PER_MINUTE = 60_000;
const SWEEP_DIR = 'sweep';
const RESULTS_FILE = 'results.jsonl';
const SUMMARY_FILE = 'summary.json';
const ORACLE_BUILD_FILE = 'oracle-build.json';
const MAX_BUFFER = 16 * 1024 * 1024;
const TIER_SET: ReadonlySet<string> = new Set(TIERS);
const VERDICT_SET: ReadonlySet<string> = new Set(VERDICTS);
const NONDETERMINISM_SOURCES: Readonly<Record<string, string>> = {
  [`${ELK_ALGORITHM_PREFIX}sporeOverlap`]:
    '`Math.random()` vertex jitter (`ElkGraphImporter.java:169`), unseedable from outside the algorithm.',
  [`${ELK_ALGORITHM_PREFIX}sporeCompaction`]:
    '`Math.random()` vertex jitter (`ElkGraphImporter.java:169`), unseedable from outside the algorithm.',
  [`${ELK_ALGORITHM_PREFIX}random`]:
    'nested composites keep the default `randomSeed = 0` (unseeded) because retarget (D2) seeds only the root.',
};

function suffixOf(algorithm: string): string {
  return algorithm.startsWith(ELK_ALGORITHM_PREFIX) ? algorithm.slice(ELK_ALGORITHM_PREFIX.length) : algorithm;
}

function compareStrings(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function parseRecord(value: unknown): SweepRecord | undefined {
  if (!isRecord(value)) return undefined;
  const { caseId, tier, algorithm, variant, modelId, verdict, ms } = value;
  const strings = [caseId, algorithm, variant, modelId].every((s) => typeof s === 'string');
  const known =
    typeof tier === 'string' && TIER_SET.has(tier) && typeof verdict === 'string' && VERDICT_SET.has(verdict);
  return strings && known && typeof ms === 'number' ? (value as unknown as SweepRecord) : undefined;
}

/** Boundary validation of results.jsonl; throws on the first malformed line. */
export function parseResults(text: string): SweepRecord[] {
  return text
    .split('\n')
    .filter((line) => line !== '')
    .map((line, i) => {
      let parsed: SweepRecord | undefined;
      try {
        parsed = parseRecord(JSON.parse(line));
      } catch {
        parsed = undefined;
      }
      if (parsed === undefined) throw new Error(`results.jsonl line ${i + 1} is not a valid sweep record`);
      return parsed;
    });
}

export function parseSummary(text: string): SweepSummary {
  const value: unknown = JSON.parse(text);
  if (isRecord(value)) {
    const { elkCommit, modelsCommit, cases, wallMs, parseErrors } = value;
    if (
      typeof elkCommit === 'string' &&
      typeof modelsCommit === 'string' &&
      typeof cases === 'number' &&
      typeof wallMs === 'number' &&
      Array.isArray(parseErrors) &&
      parseErrors.every((e) => typeof e === 'string')
    ) {
      return {
        elkCommit,
        modelsCommit,
        cases,
        wallMs,
        parseErrors: parseErrors as string[],
      };
    }
  }
  throw new Error('summary.json does not have the shape { elkCommit, modelsCommit, cases, wallMs, parseErrors }');
}

export function parsePatches(text: string): string[] {
  const value: unknown = JSON.parse(text);
  const patches = isRecord(value) ? value['patches'] : undefined;
  if (Array.isArray(patches) && patches.every((p) => typeof p === 'string')) return patches as string[];
  throw new Error(`${ORACLE_BUILD_FILE} has no string[] "patches" field`);
}

export function isStale(current: string | undefined, rendered: string): boolean {
  return current !== rendered;
}

function groupByAlgorithm(results: readonly SweepRecord[], algorithms: readonly string[]): Map<string, SweepRecord[]> {
  const groups = new Map<string, SweepRecord[]>(algorithms.map((a) => [a, []]));
  for (const r of results) {
    const group = groups.get(r.algorithm);
    if (group === undefined) {
      throw new Error(`Result algorithm ${r.algorithm} is not in the oracle algorithm list`);
    }
    group.push(r);
  }
  return groups;
}

function row(cells: readonly string[]): string {
  return `| ${cells.join(' | ')} |`;
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const alignment = header.map((_, i) => (i === 0 ? '---' : '---:'));
  return [row(header), row(alignment), ...rows.map(row)];
}

function countCell(count: number, emptyCell: string): string {
  return count === 0 ? emptyCell : String(count);
}

function matrixRow(algorithm: string, cases: readonly SweepRecord[]): string[] {
  const tierCells = TIERS.map((t) => countCell(cases.filter((c) => c.tier === t).length, TIER_EMPTY_CELLS[t]));
  const verdictCells = VERDICTS.map((v) =>
    cases.length === 0 ? NO_CASES_CELL : String(cases.filter((c) => c.verdict === v).length),
  );
  return [`\`${suffixOf(algorithm)}\``, ...tierCells, ...verdictCells, TS_CONFORMANT_CELL];
}

function matrixTable(groups: ReadonlyMap<string, readonly SweepRecord[]>): string[] {
  const header = ['algorithm', ...TIERS.map((t) => `${t} cases`), ...VERDICTS, 'TS conformant'];
  return table(
    header,
    [...groups.keys()].sort(compareStrings).map((a) => matrixRow(a, groups.get(a) ?? [])),
  );
}

function folderTable(census: Census, algorithms: readonly string[]): string[] {
  const parsed = census.models.filter((m) => m.parse === 'ok');
  const rows = [...algorithms].sort(compareStrings).map((algorithm) => {
    const own = parsed.filter((m) => m.rootAlgorithm === algorithm);
    const folders = MODEL_FOLDERS.map((f) => countCell(own.filter((m) => m.folder === f).length, NO_FOLDER_CELL));
    return [`\`${suffixOf(algorithm)}\``, ...folders, countCell(own.length, NO_NATIVE_CELL)];
  });
  return table(['algorithm (native root)', ...MODEL_FOLDERS, 'total'], rows);
}

function plural(count: number): string {
  return `${count} ${count === 1 ? 'case' : 'cases'}`;
}

function nondeterminismSection(groups: ReadonlyMap<string, readonly SweepRecord[]>): string[] {
  const lines = [...groups.keys()].sort(compareStrings).flatMap((algorithm) => {
    const count = (groups.get(algorithm) ?? []).filter((c) => c.verdict === 'nondeterministic').length;
    if (count === 0) return [];
    const cause = NONDETERMINISM_SOURCES[algorithm] ?? 'cause not yet diagnosed.';
    return [`- \`${suffixOf(algorithm)}\` (${plural(count)}): ${cause}`];
  });
  return lines.length === 0 ? [] : ['## Nondeterminism sources', '', ...lines, ''];
}

function headerLines(summary: SweepSummary, patches: readonly string[]): string[] {
  const patchList = patches.length === 0 ? 'none' : patches.map((p) => `\`${p}\``).join(', ');
  const errors = summary.parseErrors.length === 0 ? 'none' : summary.parseErrors.map((e) => `\`${e}\``).join(', ');
  return [
    `- ELK commit: \`${summary.elkCommit}\``,
    `- Models commit: \`${summary.modelsCommit}\``,
    `- Oracle seam patches: ${patchList}`,
    `- Cases: ${summary.cases}`,
    `- Sweep wall time: ${Math.round(summary.wallMs / MS_PER_MINUTE)} min`,
    `- Parse errors: ${errors}`,
  ];
}

const INTRO = [
  'One row per ELK layout algorithm (D1). The oracle is ELK built from source at the commit below,',
  'plus the seam patches listed. Every case runs in two separate JVMs; outputs must agree after',
  'identity-hash tokens (`@[0-9a-f]+`) are normalized (D5, D5a), else the verdict is `nondeterministic`.',
  'The tier columns count cases; the verdict columns count the same cases and sum to them.',
  'An empty cell names why it is empty: `—` for nothing planned, `n/a` for work that cannot exist yet.',
].join('\n');

function preamble(summary: SweepSummary, patches: readonly string[]): string[] {
  return [GENERATED_HEADER, SPDX_HEADER, '', '# Parity report', '', INTRO, '', ...headerLines(summary, patches), ''];
}

/**
 * Pure Markdown report (D9). `context.algorithms` is the oracle's `--list-algorithms`; every one
 * gets a row, and a result naming any other algorithm is a harness fault.
 */
export function renderReport(
  results: readonly SweepRecord[],
  summary: SweepSummary,
  census: Census,
  context: ReportContext,
): string {
  if (summary.cases !== results.length) {
    throw new Error(`summary.json says ${summary.cases} cases but results.jsonl has ${results.length}`);
  }
  const groups = groupByAlgorithm(results, context.algorithms);
  const lines = [
    ...preamble(summary, context.patches),
    '## Matrix',
    '',
    ...matrixTable(groups),
    '',
    '## Native-tier models per elk-models folder',
    '',
    ...folderTable(census, context.algorithms),
    '',
    ...nondeterminismSection(groups),
  ];
  return `${lines.join('\n').trimEnd()}\n`;
}

function resolveOracleDir(root: string): string {
  const override = process.env[ORACLE_DIR_ENV];
  return override !== undefined && override !== ''
    ? path.resolve(override)
    : path.resolve(root, DEFAULT_ORACLE_RELATIVE);
}

function listAlgorithms(script: string): string[] {
  const run = spawnSync(script, ['--list-algorithms'], {
    encoding: 'utf8',
    maxBuffer: MAX_BUFFER,
  });
  if (run.status !== 0) throw new Error(`run.sh --list-algorithms failed (${run.status}): ${run.stderr}`);
  const parsed: unknown = JSON.parse(run.stdout);
  if (!Array.isArray(parsed) || !parsed.every((a) => typeof a === 'string')) {
    throw new Error(`Unexpected --list-algorithms output: ${run.stdout}`);
  }
  return parsed as string[];
}

function readIfPresent(file: string): string | undefined {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return undefined;
  }
}

function buildReport(root: string): string {
  const elkCommit = readFileSync(path.join(root, ELK_COMMIT_RELATIVE), 'utf8').trim();
  const oracleDir = resolveOracleDir(root);
  const sweepDir = path.join(oracleDir, SWEEP_DIR, `${elkCommit}-${loadManifest().commit}`);
  const results = parseResults(readFileSync(path.join(sweepDir, RESULTS_FILE), 'utf8'));
  const summary = parseSummary(readFileSync(path.join(sweepDir, SUMMARY_FILE), 'utf8'));
  const census = JSON.parse(readFileSync(path.join(root, COMMITTED_CENSUS_RELATIVE), 'utf8')) as Census;
  const patches = parsePatches(readFileSync(path.join(oracleDir, ORACLE_BUILD_FILE), 'utf8'));
  const algorithms = listAlgorithms(path.join(root, RUN_SCRIPT_RELATIVE));
  return renderReport(results, summary, census, { algorithms, patches });
}

function main(argv: readonly string[]): number {
  const root = repoRoot();
  const rendered = buildReport(root);
  const target = path.join(root, REPORT_RELATIVE);
  if (argv.includes(WRITE_FLAG)) {
    writeFileSync(target, rendered);
    return 0;
  }
  if (!isStale(readIfPresent(target), rendered)) return 0;
  process.stderr.write(`${REPORT_RELATIVE} is stale; run: npx tsx tools/corpus/parity-report.ts ${WRITE_FLAG}\n`);
  return 1;
}

const entry = process.argv[1];
if (entry !== undefined && pathToFileURL(realpathSync(entry)).href === import.meta.url) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err: unknown) {
    process.stderr.write(`parity-report: ${err instanceof Error ? (err.stack ?? err.message) : String(err)}\n`);
    process.exitCode = 2;
  }
}
