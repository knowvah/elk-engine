/** Collects the TypeScript files a complexity run covers. */

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const SKIPPED_DIR_NAMES: ReadonlySet<string> = new Set(['node_modules', 'dist', 'coverage']);
const TEST_SUFFIX = '.test.ts';
const GENERATED_MARKER = 'GENERATED by tools/melk';
const GENERATED_HEADER_LINES = 5;
/** The generated option catalogue the README gate also excludes. */
const GENERATED_PATH_SUFFIXES = ['src/core/options/CoreOptions.ts'] as const;

/** Why a file is not measured, or null when it is. */
export function skipReason(path: string, text: string): string | null {
  if (path.endsWith(TEST_SUFFIX)) return 'test';
  if (GENERATED_PATH_SUFFIXES.some((s) => path.endsWith(s))) return 'generated';
  const header = text.split('\n', GENERATED_HEADER_LINES).join('\n');
  return header.includes(GENERATED_MARKER) ? 'generated' : null;
}

function walk(path: string, out: string[]): void {
  if (statSync(path).isDirectory()) {
    for (const entry of readdirSync(path).sort()) {
      if (!SKIPPED_DIR_NAMES.has(entry)) walk(join(path, entry), out);
    }
  } else if (path.endsWith('.ts')) {
    out.push(path);
  }
}

export interface Collected {
  /** Path to source text, in discovery order. */
  readonly files: Map<string, string>;
  readonly skipped: number;
}

/** Expands files and directories into measurable `.ts` files with their text. */
export function collectFiles(targets: readonly string[]): Collected {
  const paths: string[] = [];
  for (const t of targets) walk(t, paths);
  const files = new Map<string, string>();
  let skipped = 0;
  for (const path of paths) {
    const text = readFileSync(path, 'utf8');
    if (skipReason(path, text) === null) files.set(path, text);
    else skipped++;
  }
  return { files, skipped };
}
